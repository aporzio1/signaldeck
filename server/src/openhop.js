/**
 * Native MeshCore backend.
 *
 * The HAT's SX1262 can only be driven by one process at a time. Meshtastic does
 * it through meshtasticd; for MeshCore this module provisions openHop Repeater,
 * which owns the same SPI radio and exposes a companion TCP endpoint that the
 * existing MeshCore bridge speaks to. The result is a standalone device with no
 * external companion radio.
 */
export const OPENHOP = {
  dir: '/opt/openhop_repeater',
  repo: 'https://github.com/openhop-dev/openhop_repeater.git',
  service: 'openhop-repeater',
  configDir: '/etc/openhop_repeater',
  configPath: process.env.SIGNALDECK_OPENHOP_CONFIG || '/etc/openhop_repeater/config.yaml',
  identityFile: '/var/lib/openhop_repeater/identity.key',
  stateDir: '/var/lib/openhop_repeater',
};

/** MeshCore radio presets (frequency, bandwidth, spreading factor, coding-rate denominator). */
export const MESHCORE_PRESETS = [
  { id: 'us', label: 'USA / Canada · 910.525 MHz · SF7', frequency: 910525000, bandwidth: 62500, spreadingFactor: 7, codingRate: 5 },
  { id: 'eu', label: 'EU / UK · 869.618 MHz · SF8', frequency: 869618000, bandwidth: 62500, spreadingFactor: 8, codingRate: 8 },
  { id: 'au', label: 'Australia · 915.800 MHz · SF10', frequency: 915800000, bandwidth: 250000, spreadingFactor: 10, codingRate: 5 },
  { id: 'nz', label: 'New Zealand · 917.375 MHz · SF11', frequency: 917375000, bandwidth: 250000, spreadingFactor: 11, codingRate: 5 },
];

export function presetFor(id) {
  return MESHCORE_PRESETS.find((preset) => preset.id === id) || MESHCORE_PRESETS[0];
}

/** Effective native settings, with the preset applied when individual values are missing. */
export function nativeSettings(settings = getSettings()) {
  const mc = settings.lora.meshcore;
  const native = mc.native || {};
  const preset = presetFor(native.preset);
  return {
    preset: preset.id,
    frequency: Number(native.frequency) || preset.frequency,
    bandwidth: Number(native.bandwidth) || preset.bandwidth,
    spreadingFactor: Number(native.spreadingFactor) || preset.spreadingFactor,
    codingRate: Number(native.codingRate) || preset.codingRate,
    txPower: Number(native.txPower ?? 20),
    pathHashMode: Number(native.pathHashMode) || 0,
    nodeName: native.nodeName || settings.stationName || 'SignalDeck',
    adminPassword: native.adminPassword || '',
    bindAddress: native.bindAddress || '127.0.0.1',
    tcpPort: Number(native.tcpPort) || Number(mc.port) || 5000,
    radio: settings.lora.radio,
  };
}

function quote(value) {
  return JSON.stringify(String(value ?? ''));
}

/**
 * Render a complete openHop config. GPIO defaults match openHop's own
 * HackerGadgets uConsole preset (SPI1 CE0, IRQ 26, BUSY 24, RESET 25).
 */
/**
 * Pull the identity and admin password out of an existing config so a
 * regeneration never rotates the node's MeshCore identity or locks out the
 * remote CLI.
 */
export function preservedConfig(text) {
  if (!text) return {};
  const scalar = (key) => {
    const match = new RegExp(`^[\\t ]*${key}:[\\t ]*(\\S.*)$`, 'm').exec(text);
    const raw = match?.[1]?.trim();
    if (!raw || raw === 'null' || raw === '""' || raw === "''") return '';
    return raw;
  };
  const identityKey = scalar('identity_key');
  const identityFile = scalar('identity_file').replace(/^["']|["']$/g, '');
  return {
    identityKey,
    identityFile: identityFile.startsWith('/') ? identityFile : '',
    adminPassword: scalar('admin_password').replace(/^["']|["']$/g, ''),
  };
}

export function renderNativeConfig(settings = getSettings(), position = null, preserve = {}) {
  const native = nativeSettings(settings);
  const radio = native.radio || {};
  const identityFile = preserve.identityFile || OPENHOP.identityFile;
  const adminPassword = preserve.adminPassword || native.adminPassword;
  const spidev = /spidev(\d+)\.(\d+)/.exec(String(radio.spidev || ''));
  const busId = Number(spidev?.[1] ?? 0);
  const csId = Number(spidev?.[2] ?? 0);
  const csPin = radio.cs === '' || radio.cs == null ? -1 : Number(radio.cs);
  const lines = [
    '# Generated by SignalDeck — native MeshCore on the HAT SX1262.',
    '# Edit through SignalDeck (System → Native MeshCore) so pin and preset changes stay tracked.',
    'repeater:',
    `  node_name: ${quote(native.nodeName)}`,
    ...(preserve.identityKey ? [`  identity_key: ${preserve.identityKey}`] : []),
    `  identity_file: ${quote(identityFile)}`,
    position && Number.isFinite(position.lat) ? `  latitude: ${position.lat}` : '  latitude: null',
    position && Number.isFinite(position.lon) ? `  longitude: ${position.lon}` : '  longitude: null',
    '  guest_password: ""',
    adminPassword ? `  admin_password: ${quote(adminPassword)}` : '  admin_password: ""',
    '  allow_read_only: true',
    '',
    'radio_type: sx1262',
    'sx1262:',
    `  bus_id: ${busId}`,
    `  cs_id: ${csId}`,
    `  cs_pin: ${Number.isFinite(csPin) ? csPin : -1}`,
    `  reset_pin: ${Number(radio.reset ?? 25)}`,
    `  busy_pin: ${Number(radio.busy ?? 24)}`,
    `  irq_pin: ${Number(radio.irq ?? 26)}`,
    '  txen_pin: -1',
    '  rxen_pin: -1',
    `  use_dio3_tcxo: ${radio.dio3Tcxo === false ? 'false' : 'true'}`,
    '  dio3_tcxo_voltage: 1.8',
    `  use_dio2_rf: ${radio.dio2RfSwitch === false ? 'false' : 'true'}`,
    '',
    'radio:',
    `  frequency: ${native.frequency}`,
    `  tx_power: ${native.txPower}`,
    `  bandwidth: ${native.bandwidth}`,
    `  spreading_factor: ${native.spreadingFactor}`,
    `  coding_rate: ${native.codingRate}`,
    '  preamble_length: 32',
    '  sync_word: 0x12',
    '',
    'identities:',
    '  companions:',
    '    - name: "signaldeck"',
    '      settings:',
    `        node_name: ${quote(native.nodeName)}`,
    `        tcp_port: ${native.tcpPort}`,
    `        bind_address: ${quote(native.bindAddress)}`,
    '        tcp_timeout: 120',
    '',
    'mesh:',
    `  path_hash_mode: ${native.pathHashMode}`,
    '',
    'storage:',
    `  storage_dir: ${quote(OPENHOP.stateDir)}`,
    '',
    'http:',
    '  enabled: false',
    '  host: "127.0.0.1"',
    '  port: 8000',
    '',
    'plugins:',
    '  enabled: false',
    '',
  ];
  return lines.join('\n');
}

const CONFIG_CACHE_MS = 8000;
let configCache = null;

function sudoCouldNotAnswer(res) {
  return /password is required|not allowed|not in the sudoers|a terminal is required|command not found/i.test(res.stderr || '');
}

async function readConfigFile(file) {
  const direct = await readText(file, 512 * 1024);
  if (direct != null) return { text: direct, source: 'file' };
  if (!isLinux) return null;
  // The file is normally owned by openHop's service user (mode 0600).
  const cat = await run('sudo', ['-n', 'cat', file], { timeout: 6000, maxBuffer: 1024 * 1024 });
  return cat.ok ? { text: cat.stdout, source: 'sudo' } : null;
}

/**
 * Probe the installed config without guessing. `exists` is true, false (proven
 * absent) or null (cannot be determined). Callers must refuse to write unless
 * the file is proven absent or has been read successfully: writing over an
 * identity we cannot see would rotate the node's MeshCore key.
 */
async function probeNativeConfig() {
  const path = OPENHOP.configPath;
  let stat = null;
  let statError = null;
  try {
    stat = await fsp.stat(path);
  } catch (err) {
    statError = err;
  }

  if (!stat && statError?.code === 'ENOENT') {
    return { path, exists: false, readable: false, text: '', source: 'none', error: null };
  }

  if (!stat) {
    if (!isLinux) {
      return {
        path,
        exists: null,
        readable: false,
        text: '',
        source: 'none',
        error: `Cannot verify ${path} (${statError?.code || 'stat failed'}). Native MeshCore applies are blocked to protect the node identity.`,
      };
    }
    const test = await run('sudo', ['-n', 'test', '-f', path], { timeout: 5000 });
    if (!test.ok) {
      if (test.code === 1 && !sudoCouldNotAnswer(test)) {
        return { path, exists: false, readable: false, text: '', source: 'none', error: null };
      }
      return {
        path,
        exists: null,
        readable: false,
        text: '',
        source: 'none',
        error: `Cannot verify whether ${path} exists. Native MeshCore applies are blocked to protect the node identity; re-run install.sh to refresh the sudoers rules.`,
      };
    }
  }

  if (stat && !stat.isFile()) {
    return {
      path,
      exists: true,
      readable: false,
      text: '',
      source: 'none',
      error: `${path} is not a regular file; native MeshCore applies are blocked.`,
    };
  }

  const read = await readConfigFile(path);
  if (read) {
    return { path, exists: true, readable: true, text: read.text, source: read.source, error: null };
  }
  return {
    path,
    exists: true,
    readable: false,
    text: '',
    source: 'none',
    error: `Cannot read ${path}. Native MeshCore applies are blocked so the existing identity is not replaced; re-run install.sh to refresh the sudoers rule for this file.`,
  };
}

export async function inspectNativeConfig({ fresh = false } = {}) {
  if (!fresh && configCache && Date.now() - configCache.at < CONFIG_CACHE_MS) return configCache.value;
  const value = await probeNativeConfig();
  configCache = { at: Date.now(), value };
  return value;
}

export function invalidateNativeConfigCache() {
  configCache = null;
}

/** Read the config, returning '' when it is absent or cannot be read. */
export async function readNativeConfig() {
  const info = await inspectNativeConfig();
  return info.readable ? info.text : '';
}

export async function waitForTcp(host, port, timeoutMs = 20000) {
  const started = Date.now();
  while (Date.now() - started < timeoutMs) {
    const ok = await new Promise((resolve) => {
      const socket = net.connect({ host, port });
      const done = (value) => {
        socket.removeAllListeners();
        socket.destroy();
        resolve(value);
      };
      socket.setTimeout(1200);
      socket.once('connect', () => done(true));
      socket.once('timeout', () => done(false));
      socket.once('error', () => done(false));
    });
    if (ok) return true;
    await new Promise((resolve) => setTimeout(resolve, 700));
  }
  return false;
}

export async function nativeState(settings = getSettings(), options = {}) {
  const native = nativeSettings(settings);
  const [service, config] = await Promise.all([serviceStatus(OPENHOP.service), inspectNativeConfig()]);
  const installed = fs.existsSync(OPENHOP.dir) && config.exists === true;
  const companionReachable = isLinux && options.probe ? await waitForTcp(native.bindAddress, native.tcpPort, 900) : false;
  return {
    backend: 'openhop',
    installed,
    configPath: OPENHOP.configPath,
    config: { path: config.path, exists: config.exists, readable: config.readable, source: config.source, error: config.error },
    serviceDir: OPENHOP.dir,
    service,
    active: service.active,
    companion: { host: native.bindAddress, port: native.tcpPort, reachable: companionReachable },
    preset: native.preset,
    frequency: native.frequency,
    bandwidth: native.bandwidth,
    spreadingFactor: native.spreadingFactor,
    codingRate: native.codingRate,
    txPower: native.txPower,
    nodeName: native.nodeName,
    identityFile: OPENHOP.identityFile,
    presets: MESHCORE_PRESETS,
  };
}

/** Validate loosely, then install the config with a timestamped backup and a restart. */
export async function writeNativeConfig(text, restart = false) {
  if (!isLinux) throw Object.assign(new Error('Native MeshCore configuration requires Linux.'), { status: 400 });
  if (typeof text !== 'string' || text.length > 128 * 1024) {
    throw Object.assign(new Error('Configuration text is missing or too large.'), { status: 400 });
  }
  if (!/^repeater:/m.test(text)) throw Object.assign(new Error('The config must contain a repeater: section.'), { status: 400 });
  if (!/^radio_type:/m.test(text)) throw Object.assign(new Error('The config must define radio_type:.'), { status: 400 });

  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  await run('sudo', ['-n', 'mkdir', '-p', OPENHOP.configDir], { timeout: 6000 });
  const existing = await run('sudo', ['-n', 'test', '-f', OPENHOP.configPath], { timeout: 5000 });
  if (existing.ok) {
    await run('sudo', ['-n', 'cp', OPENHOP.configPath, `${OPENHOP.configPath}.signaldeck-${stamp}.bak`], { timeout: 8000 });
  }

  const tmp = `/tmp/signaldeck-openhop-${process.pid}.yaml`;
  await fs.promises.writeFile(tmp, text, { mode: 0o600 });
  const copied = await run('sudo', ['-n', 'cp', tmp, OPENHOP.configPath], { timeout: 8000 });
  await fs.promises.unlink(tmp).catch(() => {});
  if (copied.ok) {
    // openHop runs as a dedicated unprivileged user; hand it the config so it
    // can read the generated password and identity path.
    const owner = await serviceUser();
    await run('sudo', ['-n', 'chown', owner, OPENHOP.configPath], { timeout: 6000 });
    invalidateNativeConfigCache();
  }
  if (!copied.ok) {
    throw Object.assign(
      new Error(copied.stderr || 'Could not write the openHop config (check the sudoers rules from install.sh).'),
      { status: 500 },
    );
  }

  let restarted = false;
  if (restart) restarted = await restartNative();
  return { ok: true, path: OPENHOP.configPath, backup: existing.ok ? `${OPENHOP.configPath}.signaldeck-${stamp}.bak` : null, restarted };
}

export async function serviceUser() {
  if (!isLinux) return 'root';
  const res = await run('systemctl', ['show', '-p', 'User', '--value', OPENHOP.service], { timeout: 4000 });
  return (res.ok && res.stdout.trim()) || 'root';
}

export async function restartNative() {
  if (!isLinux) return false;
  await run('sudo', ['-n', 'systemctl', 'enable', OPENHOP.service], { timeout: 15000 });
  const res = await run('sudo', ['-n', 'systemctl', 'restart', OPENHOP.service], { timeout: 30000 });
  return res.ok;
}

export async function stopNative() {
  if (!isLinux) return false;
  const res = await run('sudo', ['-n', 'systemctl', 'stop', OPENHOP.service], { timeout: 20000 });
  return res.ok;
}
